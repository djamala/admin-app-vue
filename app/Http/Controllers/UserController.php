     * Display a listing of the resource.
     */
     public function index()
    {
        $users = User::select('id', 'name', 'email', 'status')
            ->with('roles:id,name') // relation Spatie
            ->get()
            ->map(fn (User $user) => [
                'id' => $user->id,
                'name' => $user->name,
                'email' => $user->email,
                'status' => $user->status,
                // On aplatit le(s) rôle(s) en une seule string pour le front
                'role' => $user->roles->pluck('name')->first(),
                // Ou, si un user peut avoir plusieurs rôles :
                // 'roles' => $user->roles->pluck('name'),
            ]);

        return Inertia::render('users/Index', [
            'usersData' => $users,
        ]);
    }

